/**
 * Apply jitter to coordinates to prevent overlapping markers
 * @param lat - Base latitude
 * @param lon - Base longitude
 * @param jitterAmount - Maximum jitter offset in degrees (default ±0.05)
 * @returns Jittered coordinates [lat, lon]
 */
export function applyJitter(
  lat: number, 
  lon: number, 
  jitterAmount: number = 0.05
): [number, number] {
  const jitterLat = (Math.random() - 0.5) * 2 * jitterAmount;
  const jitterLon = (Math.random() - 0.5) * 2 * jitterAmount;
  return [lat + jitterLat, lon + jitterLon];
}

/**
 * Get coordinates for a Texas county, with optional jitter
 * @param county - County name
 * @param withJitter - Whether to apply jitter
 * @returns Coordinates [lat, lon] or null if county not found
 */
export function getTexasCountyCoordinates(
  county: string, 
  withJitter: boolean = true
): [number, number] | null {
  // Normalize county name (handle variations like "HARRIS" vs "Harris")
  const normalizedCounty = county.trim().split(' ')
    .map(word => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
    .join(' ');
  
  const coords = TEXAS_COUNTY_CENTROIDS[normalizedCounty];
  if (!coords) return null;
  
  if (withJitter) {
    return applyJitter(coords[0], coords[1]);
  }
  
  return coords;
}
